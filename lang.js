/* =========================================================
   CHANGE LANGUAGE
========================================================= */

function setLanguage(language) {

    language = normalizeArchiveLanguage(language);

    if (!translations[language]) {
        language = "en";
    }


    currentLanguage =
        language;

    document.documentElement.lang = language;


    localStorage.setItem(
        "silverPalaceLanguage",
        language
    );


    const selector =
        document.getElementById(
            "languageSelect"
        );


    if (selector) {
        selector.value = language;
    }


    translatePage();


    /*
        Re-render characters / Motives and rankings
        after script.js has loaded.
    */

    if (
        typeof window.refreshDynamicContent
        === "function"
    ) {

        window.refreshDynamicContent();

    }

}


/* =========================================================
   LANGUAGE SELECTOR
========================================================= */

const languageSelect =
    document.getElementById(
        "languageSelect"
    );


if (languageSelect) {

    languageSelect.value =
        currentLanguage;


    languageSelect.addEventListener(
        "change",
        function () {

            setLanguage(
                languageSelect.value
            );

        }
    );

}


