/* =========================================================
   CHANGE LANGUAGE
========================================================= */

function setLanguage(language) {

    if (!translations[language]) {
        language = "en";
    }


    currentLanguage =
        language;


    localStorage.setItem(
        "silverPalaceLanguage",
        language
    );


    const selector =
        document.getElementById(
            "languageSelect"
        );


    if (selector) {
        selector.value = language;
    }


    translatePage();


    /*
        Re-render characters / Motives and rankings
        after script.js has loaded.
    */

    if (
        typeof window.refreshDynamicContent
        === "function"
    ) {

        window.refreshDynamicContent();

    }

}


