import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const root = process.cwd();
const queuePath = path.join(root, "content/publish-schedule.js");
const now = process.env.TDA_PUBLISH_NOW ? new Date(process.env.TDA_PUBLISH_NOW) : new Date();

const typeMap = {
  news: { file: "content/news.js", variable: "newsData" },
  character: { file: "content/characters.js", variable: "charactersData" },
  motive: { file: "content/motives.js", variable: "weaponsData" },
  simulation: { file: "content/simulation.js", variable: "simulationData", info: "simulationSystemInfo" },
  epiphany: { file: "content/epiphanies.js", variable: "epiphanyData", info: "epiphanySystemInfo" }
};

const translationCollection = {
  news: "news",
  character: "characters",
  motive: "motives",
  simulation: "simulation",
  epiphany: "epiphanies"
};

function ensureParent(file) { fs.mkdirSync(path.dirname(file), { recursive: true }); }

function loadQueue() {
  if (!fs.existsSync(queuePath)) return { version: 1, timezone: "Asia/Ho_Chi_Minh", items: [] };
  const source = fs.readFileSync(queuePath, "utf8");
  const sandbox = { window: {} };
  vm.runInNewContext(source, sandbox, { filename: queuePath });
  const queue = sandbox.window.ArchivePublishSchedule || {};
  if (!Array.isArray(queue.items)) queue.items = [];
  return queue;
}

function writeQueue(queue) {
  const text = `/* =========================================================
   THE DETECTIVE ARCHIVE — PUBLISH SCHEDULE
   Public metadata only. Scheduled record payloads live in /scheduled/
   and are excluded from the deployed GitHub Pages artifact.
========================================================= */

window.ArchivePublishSchedule = ${JSON.stringify(queue, null, 4)};
`;
  ensureParent(queuePath);
  fs.writeFileSync(queuePath, text);
}

function loadContent(type) {
  const config = typeMap[type];
  if (!config) throw new Error(`Unsupported scheduled type: ${type}`);
  const file = path.join(root, config.file);
  const source = fs.readFileSync(file, "utf8");
  const sandbox = {};
  const capture = [`globalThis.__data = typeof ${config.variable} !== \"undefined\" ? ${config.variable} : [];`];
  if (config.info) capture.push(`globalThis.__info = typeof ${config.info} !== \"undefined\" ? ${config.info} : null;`);
  vm.runInNewContext(`${source}\n;${capture.join("\n")}`, sandbox, { filename: file });
  return { file, config, list: JSON.parse(JSON.stringify(sandbox.__data || [])), info: sandbox.__info ? JSON.parse(JSON.stringify(sandbox.__info)) : null };
}

function writeContent(type, state) {
  const { file, config, list } = state;
  let text = `/* The Detective Archive · Scheduled Publisher
   Published automatically from the verified schedule queue.
   Unknown / unverified Silver Palace values should remain blank. */

const ${config.variable} = ${JSON.stringify(list, null, 4)};
`;
  if (config.info && state.info) {
    if (type === "epiphany" && Object.prototype.hasOwnProperty.call(state.info, "count")) state.info.count = list.length;
    text += `\nconst ${config.info} = ${JSON.stringify(state.info, null, 4)};\n`;
  }
  fs.writeFileSync(file, text);
}

function upsertRecord(type, record) {
  if (!record || !record.id) throw new Error(`Scheduled ${type} payload is missing record.id`);
  const state = loadContent(type);
  const index = state.list.findIndex(item => item && item.id === record.id);
  if (index >= 0) state.list[index] = record;
  else if (type === "news") state.list.unshift(record);
  else state.list.push(record);
  writeContent(type, state);
}

function loadTranslations() {
  const file = path.join(root, "locales/archive-content-translations.js");
  if (!fs.existsSync(file)) return { file, store: {} };
  const source = fs.readFileSync(file, "utf8");
  const sandbox = { window: {}, registerArchiveLocale() {} };
  vm.runInNewContext(source, sandbox, { filename: file });
  return { file, store: JSON.parse(JSON.stringify(sandbox.window.ArchiveContentTranslations || {})) };
}

function writeTranslations(file, store) {
  const text = `/* =========================================================
   THE DETECTIVE ARCHIVE — RECORD CONTENT TRANSLATIONS

   Generated by Archive Content Studio.
   English source text remains in /content/*.js.
   Missing translations safely fall back to English.
========================================================= */

window.ArchiveContentTranslations = ${JSON.stringify(store, null, 4)};

(function applyArchiveContentTranslationFile() {
    if (typeof registerArchiveLocale !== \"function\") return;
    Object.keys(window.ArchiveContentTranslations).forEach(function (language) {
        registerArchiveLocale(language, { content: window.ArchiveContentTranslations[language] });
    });
})();
`;
  ensureParent(file);
  fs.writeFileSync(file, text);
}

function applyTranslations(type, recordId, translations) {
  if (!translations || typeof translations !== "object") return;
  const collection = translationCollection[type];
  if (!collection) return;
  const state = loadTranslations();
  for (const [language, overlay] of Object.entries(translations)) {
    if (!overlay || typeof overlay !== "object" || !Object.keys(overlay).length) continue;
    if (!state.store[language] || typeof state.store[language] !== "object") state.store[language] = {};
    if (!state.store[language][collection] || typeof state.store[language][collection] !== "object") state.store[language][collection] = {};
    state.store[language][collection][recordId] = overlay;
  }
  writeTranslations(state.file, state.store);
}

function applyAssets(payload) {
  for (const asset of Array.isArray(payload.assets) ? payload.assets : []) {
    if (!asset || !asset.source || !asset.target) continue;
    const source = path.join(root, asset.source);
    const target = path.join(root, asset.target);
    if (!fs.existsSync(source)) {
      if (fs.existsSync(target)) continue;
      throw new Error(`Scheduled asset not found: ${asset.source}`);
    }
    ensureParent(target);
    fs.copyFileSync(source, target);
    fs.rmSync(source, { force: true });
  }
}

function removeEmptyParents(file, stopRelative) {
  let current = path.dirname(file);
  const stop = path.join(root, stopRelative);
  while (current.startsWith(stop) && current !== stop) {
    if (!fs.existsSync(current) || fs.readdirSync(current).length) break;
    fs.rmdirSync(current);
    current = path.dirname(current);
  }
}

function cleanupOrphans(queue) {
  const referencedPayloads = new Set((queue.items || []).map(item => item.payloadPath).filter(Boolean));
  const referencedIds = new Set((queue.items || []).map(item => item.scheduleId).filter(Boolean));
  const recordDir = path.join(root, "scheduled/records");
  if (fs.existsSync(recordDir)) {
    for (const name of fs.readdirSync(recordDir)) {
      const rel = `scheduled/records/${name}`;
      if (!referencedPayloads.has(rel)) fs.rmSync(path.join(recordDir, name), { force: true });
    }
  }
  const assetDir = path.join(root, "scheduled/assets");
  if (fs.existsSync(assetDir)) {
    for (const name of fs.readdirSync(assetDir)) {
      if (!referencedIds.has(name)) fs.rmSync(path.join(assetDir, name), { recursive: true, force: true });
    }
  }
}

const queue = loadQueue();
const remaining = [];
let published = 0;

for (const item of queue.items) {
  const publishTime = new Date(item.publishAt);
  const due = item.enabled !== false && !Number.isNaN(publishTime.getTime()) && publishTime.getTime() <= now.getTime();
  if (!due) { remaining.push(item); continue; }

  const payloadFile = path.join(root, item.payloadPath || "");
  if (!item.payloadPath || !fs.existsSync(payloadFile)) throw new Error(`Missing scheduled payload for ${item.scheduleId || item.recordId}`);
  const payload = JSON.parse(fs.readFileSync(payloadFile, "utf8"));
  if (payload.type !== item.type) throw new Error(`Type mismatch in scheduled payload ${item.scheduleId}`);
  if (!payload.record || payload.record.id !== item.recordId) throw new Error(`Record ID mismatch in scheduled payload ${item.scheduleId}`);

  upsertRecord(item.type, payload.record);
  applyTranslations(item.type, item.recordId, payload.translations);
  applyAssets(payload);
  fs.rmSync(payloadFile, { force: true });
  removeEmptyParents(payloadFile, "scheduled/records");
  published += 1;
  console.log(`[TDA] Published ${item.type}:${item.recordId} scheduled for ${item.publishAt}`);
}

queue.items = remaining;
cleanupOrphans(queue);
writeQueue(queue);
console.log(`[TDA] Scheduled publishing complete. Published: ${published}; Pending: ${remaining.length}.`);
